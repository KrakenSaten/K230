static void poll_status(struct system_app *a);

static void on_tab(lv_event_t *e)
{
    struct system_app *a = lv_event_get_user_data(e);
    intptr_t t = (intptr_t)lv_obj_get_user_data(lv_event_get_current_target(e));

    if (t < 0 || t >= SYSTEM_TAB_COUNT || t == (intptr_t)a->tab) {
        return;
    }
    a->tab = (enum system_tab)t;
    a->tick = 0;
    if (a->tab == SYSTEM_TAB_NETWORK) {
        /* The page's own three answers once now, so it opens with them;
         * after this, one a tick in turn. */
        int k;

        a->net_step = SYSTEM_NET_RADIO;
        for (k = 0; k < SYSTEM_NET_STEPS; k++) {
            system_net_poll_step(a);
        }
    }
    rebuild(a);
}

/* Four buttons across the top, the page on show accented, and the freshness
 * line: under them when the body is tall, at the end of their row when it is
 * wide (arrange_live), where it costs no line of its own. The buttons wrap
 * onto a second line rather than shrink below a finger's width when the text
 * size makes their words wider than a quarter of the body. */
static void build_tabs(struct system_app *a)
{
    lv_obj_t *r = lv_obj_create(a->body);
    int i;

    lv_obj_remove_style_all(r);
    lv_obj_set_size(r, LV_PCT(100), LV_SIZE_CONTENT);
    lv_obj_set_flex_flow(r, LV_FLEX_FLOW_ROW_WRAP);
    lv_obj_set_flex_align(r, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_CENTER, LV_FLEX_ALIGN_CENTER);
    lv_obj_set_style_pad_column(r, 8, 0);
    lv_obj_set_style_pad_row(r, 8, 0);
    lv_obj_clear_flag(r, LV_OBJ_FLAG_SCROLLABLE);
    a->tabs = r;
    for (i = 0; i < SYSTEM_TAB_COUNT; i++) {
        lv_obj_t *b = pocketui_button(r, tab_labels[i], on_tab, a);

        restrain(b);
        pos_style_add(b, POS_STYLE_SLAB_PRESSED, LV_STATE_PRESSED);
        lv_obj_set_height(b, SYSTEM_ACTION_BTN_H);
        lv_obj_set_width(b, LV_SIZE_CONTENT);
        lv_obj_set_style_min_width(b, POCKETUI_TOUCH_MIN, 0);
        lv_obj_set_style_pad_hor(b, 12, 0);
        lv_obj_set_flex_grow(b, 1);
        lv_obj_set_user_data(b, (void *)(intptr_t)i);
        a->tab_btn[i] = b;
    }
    /* ABOUT shows nothing live, so it has no freshness to report. */
    if (a->tab != SYSTEM_TAB_ABOUT) {
        a->freshness = pocketui_label(r, a->view.freshness, POS_STYLE_CAPTION);
        lv_obj_set_style_text_align(a->freshness, LV_TEXT_ALIGN_RIGHT, 0);
    }
}

