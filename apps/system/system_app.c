/* ---- the layout -------------------------------------------------------- *
 *
 * The screen sits in one frame that is exactly the body's content box - the
 * whole of the room the shell gives the app - and is arranged from the size
 * of that box alone:
 *
 *   TALL (portrait: 528 x 1060 on the reference panel). The tabs, the
 *   freshness line, then the page's panels one above the other.
 *
 *   WIDE (landscape: 1192 x 396). The tabs with the freshness line at the
 *   end of their row, and the page's two columns side by side with the DS 7
 *   panel gap between them: the machine's vitals beside storage and the
 *   actions, the interfaces beside the links. A page with one column (the
 *   services, the identity) keeps it across the body. A confirmation, or
 *   the panel a power action leaves, keeps its
 *   portrait width, centred, with the freshness line over it at the same
 *   width (DS 23.4). Chosen only when each half keeps SYSTEM_COLUMN_W, so no
 *   panel, row or button is narrower than in portrait. No control takes its
 *   size from the height, so no body can bring one under its DS 7 size.
 *
 * In either shape the page itself is the one box that scrolls, and only when
 * what it holds is taller than the room: nothing inside it scrolls (DS
 * §52.2; v0.0.10 to v0.3.0 had a column for each half that scrolled on its
 * own in landscape).
 *
 * The body is built as it always was - when what it holds changes shape - and
 * arranged when it is built. A change of the frame's size only arranges: flow
 * and widths. The objects, their values, the phase and a refused action's
 * reason are not touched by it.
 *
 * Whatever the shape, nothing is drawn into the panel's unsafe area (DS 21.1,
 * 22.2): a scrolled page passes the foot of the body, which reaches 10 px into
 * the 30 px corner squares of the reference panel, so the frame pads its foot
 * by however far a corner square reaches into the body, from the platform's
 * description (pos_display_rect_insets, the rule Calculator and Notes use).
 * On a panel with square corners the pad is 0. */

/* Tall: the tabs, the freshness line under them, and one column. Wide: the
 * freshness line at the end of the tabs' row, and the two columns side by
 * side - or the one, across. */
/* The tabs share their row while their words fit it, each an equal share of
 * it; when the text size makes the widest of the four wider than its share
 * (Medium and Large in portrait), they go two to a line, each half the row,
 * rather than squeeze a word past its button's edge. Measured from the words
 * and the fonts, not from anything laid out, so it holds inside a layout
 * pass. */
static void arrange_tabs(struct system_app *a)
{
    int32_t widest = 0;
    bool pairs;
    int i;

    if (a->full_w <= 0) {
        return; /* not laid out yet: the first layout pass arranges them */
    }
    for (i = 0; i < SYSTEM_TAB_COUNT; i++) {
        lv_obj_t *b = a->tab_btn[i];
        lv_obj_t *lb = b ? lv_obj_get_child(b, 0) : NULL;
        lv_point_t size;

        if (!lb) {
            return;
        }
        lv_text_get_size(&size, lv_label_get_text(lb), lv_obj_get_style_text_font(lb, LV_PART_MAIN),
                         lv_obj_get_style_text_letter_space(lb, LV_PART_MAIN), 0, LV_COORD_MAX, LV_TEXT_FLAG_NONE);
        size.x += lv_obj_get_style_pad_left(b, LV_PART_MAIN) + lv_obj_get_style_pad_right(b, LV_PART_MAIN) +
                  2 * lv_obj_get_style_border_width(b, LV_PART_MAIN) + 4;
        widest = LV_MAX(widest, size.x);
    }
    pairs = SYSTEM_TAB_COUNT * widest + (SYSTEM_TAB_COUNT - 1) * 8 > a->full_w;
    for (i = 0; i < SYSTEM_TAB_COUNT; i++) {
        lv_obj_set_flex_grow(a->tab_btn[i], pairs ? 0 : 1);
        lv_obj_set_width(a->tab_btn[i], pairs ? (a->full_w - 8) / 2 : LV_SIZE_CONTENT);
    }
}

static void arrange_live(struct system_app *a)
{
    bool two;

    arrange_tabs(a);
    lv_obj_set_flex_flow(a->body, LV_FLEX_FLOW_COLUMN);
    lv_obj_set_flex_align(a->body, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_START);
    if (a->freshness && lv_obj_get_parent(a->freshness) == a->tabs) {
        lv_obj_set_width(a->freshness, a->wide ? LV_SIZE_CONTENT : LV_PCT(100));
        lv_obj_set_style_min_width(a->freshness, a->wide ? 96 : 0, 0);
    }
    if (!a->cols) {
        return;
    }
    two = lv_obj_get_child_count(a->col[1]) > 0;
    lv_obj_set_flex_flow(a->cols, a->wide ? LV_FLEX_FLOW_ROW : LV_FLEX_FLOW_COLUMN);
    lv_obj_set_width(a->col[0], a->wide && two ? a->half_w : LV_PCT(100));
    lv_obj_set_width(a->col[1], a->wide ? a->half_w : LV_PCT(100));
    if (two) {
        lv_obj_clear_flag(a->col[1], LV_OBJ_FLAG_HIDDEN);
    } else {
        lv_obj_add_flag(a->col[1], LV_OBJ_FLAG_HIDDEN);
    }
}

/* Across the body when tall; the portrait width, centred, when wide, the
 * freshness line over it at the same width. The body scrolls in either. */
static void arrange_dialog(struct system_app *a)
{
    int32_t w = a->wide ? SYSTEM_COLUMN_W : LV_PCT(100);
    lv_flex_align_t across = a->wide ? LV_FLEX_ALIGN_CENTER : LV_FLEX_ALIGN_START;

    /* The body's one track is as wide as the widest of the two, so it is the
     * track that is centred, and the two in it. */
    lv_obj_set_flex_flow(a->body, LV_FLEX_FLOW_COLUMN);
    lv_obj_set_flex_align(a->body, LV_FLEX_ALIGN_START, across, across);
    lv_obj_set_width(a->dialog, w);
    if (a->freshness_row) {
        lv_obj_set_width(a->freshness_row, w);
    }
}

static void arrange(struct system_app *a)
{
    if (!a->body) {
        return;
    }
    if (a->diag) {
        /* One column in either shape: log lines are better read across the
         * whole width than squeezed into half of it. */
        lv_obj_set_flex_flow(a->body, LV_FLEX_FLOW_COLUMN);
        return;
    }
    if (a->dialog) {
        arrange_dialog(a);
    } else {
        arrange_live(a);
    }
}

static void layout(struct system_app *a)
{
    struct pos_insets in;
    const lv_area_t *box;
    int32_t w;
    int32_t h;

    /* Nothing to lay out in, or nothing the layout is chosen from has
     * changed: PocketUI owns that decision for every responsive app, and
     * hands back the corner clearance the platform rule gives this box. */
    if (!pocketui_layout_begin(&a->layout_guard, a->frame, &in)) {
        return;
    }
    box = &a->layout_guard.area;
    lv_obj_set_style_pad_left(a->frame, in.left, 0);
    lv_obj_set_style_pad_top(a->frame, in.top, 0);
    lv_obj_set_style_pad_right(a->frame, in.right, 0);
    lv_obj_set_style_pad_bottom(a->frame, in.bottom, 0);
    w = lv_area_get_width(box) - in.left - in.right;
    h = lv_area_get_height(box) - in.top - in.bottom;
    a->wide = w > h && w >= 2 * SYSTEM_COLUMN_W + SYSTEM_PANEL_GAP;
    a->full_w = w;
    a->half_w = (w - SYSTEM_PANEL_GAP) / 2;
    arrange(a);
}

/* The frame is the body's content box, so this is the body changing size:
 * the display turned under the open app, or this is the first layout pass
 * after the app was built. */
static void on_frame_size(lv_event_t *e)
{
    layout(lv_event_get_user_data(e));
}

static void build_frame(struct system_app *a)
{
    lv_obj_t *frame = lv_obj_create(a->root);

    lv_obj_remove_style_all(frame);
    /* Exactly the body's content box, whatever is in it, so the shape is
     * always chosen from the room the shell gives and never from the size of
     * what the arrangement itself put there. */
    lv_obj_set_size(frame, LV_PCT(100), LV_PCT(100));
    lv_obj_clear_flag(frame, LV_OBJ_FLAG_SCROLLABLE);
    a->frame = frame;
}

/* The body is rebuilt only when its shape changes - another page, a service
 * appearing, the card row starting to disagree, a dialog opening - and
 * repainted in place every other second otherwise, so a scroll position
 * survives a poll. */
static void rebuild(struct system_app *a)
{
    const struct system_view *v = &a->view;

    if (a->body) {
        lv_obj_delete(a->body);
    }
    a->tabs = NULL;
    memset(a->tab_btn, 0, sizeof(a->tab_btn));
    a->cols = NULL;
    memset(a->col, 0, sizeof(a->col));
    a->freshness_row = NULL;
    a->dialog = NULL;
    memset(a->vital, 0, sizeof(a->vital));
    memset(a->mount_detail, 0, sizeof(a->mount_detail));
    memset(a->mount_bar, 0, sizeof(a->mount_bar));
    a->expand_line = NULL;
    memset(a->svc_chip, 0, sizeof(a->svc_chip));
    memset(a->svc_detail, 0, sizeof(a->svc_detail));
    memset(&a->net, 0, sizeof(a->net));
    a->freshness = NULL;
    a->toast = NULL;
    memset(a->diag_value, 0, sizeof(a->diag_value));
    memset(a->diag_filter, 0, sizeof(a->diag_filter));
    a->diag_state = NULL;
    a->diag_crash_box = NULL;
    a->diag_log_box = NULL;
    a->diag_log_status = NULL;

    a->body = lv_obj_create(a->frame);
    lv_obj_remove_style_all(a->body);
    lv_obj_set_width(a->body, LV_PCT(100));
    lv_obj_set_height(a->body, LV_PCT(100));
    lv_obj_set_flex_flow(a->body, LV_FLEX_FLOW_COLUMN);
    lv_obj_set_style_pad_row(a->body, SYSTEM_PANEL_GAP, 0);
    lv_obj_set_style_pad_column(a->body, SYSTEM_PANEL_GAP, 0);
    lv_obj_set_scroll_dir(a->body, LV_DIR_VER);
    lv_obj_set_scrollbar_mode(a->body, LV_SCROLLBAR_MODE_AUTO);

    if (a->diag && v->phase == SYSTEM_VIEW_LIVE) {
        build_diag(a);
    } else if (v->phase == SYSTEM_VIEW_TERMINAL_REBOOT || v->phase == SYSTEM_VIEW_TERMINAL_POWEROFF) {
        /* Nothing is being polled any more, so there is no freshness to
         * report and claiming one would be a lie. */
        build_terminal(a);
    } else if (v->phase == SYSTEM_VIEW_CONFIRM_REBOOT || v->phase == SYSTEM_VIEW_CONFIRM_POWEROFF ||
               v->phase == SYSTEM_VIEW_CONFIRM_EXPAND) {
        build_freshness(a);
        build_confirm(a);
    } else {
        int i;

        build_tabs(a);
        /* toast: the reason a refused action gave, above the page */
        a->toast = system_wrap_label(a->body, "", POS_STYLE_STATUS_ERROR_TEXT);
        lv_obj_add_flag(a->toast, LV_OBJ_FLAG_HIDDEN);
        a->cols = stack(a->body);
        for (i = 0; i < 2; i++) {
            a->col[i] = stack(a->cols);
        }
        switch (a->tab) {
        case SYSTEM_TAB_NETWORK:
            system_net_build(a);
            break;
        case SYSTEM_TAB_SERVICES:
            build_services(a);
            break;
        case SYSTEM_TAB_ABOUT:
            build_about(a);
            break;
        case SYSTEM_TAB_OVERVIEW:
        default:
            build_overview(a);
            break;
        }
    }
    a->built_mounts = v->mount_count;
    a->built_ifaces = v->iface_count;
    a->built_services = v->service_count;
    a->built_card = v->show_card;
    a->built_phase = v->phase;
    a->built_expand = v->expand;
    a->built_diag = a->diag;
    a->built_tab = a->tab;
    arrange(a);
    repaint(a);
    diag_repaint(a);
}

static int shape_changed(const struct system_app *a)
{
    const struct system_view *v = &a->view;

    return a->built_mounts != v->mount_count || a->built_ifaces != v->iface_count ||
           a->built_services != v->service_count || a->built_card != v->show_card ||
           a->built_phase != v->phase || a->built_diag != a->diag || a->built_tab != a->tab ||
           a->built_expand != v->expand;
}

/* ---- app lifecycle ----------------------------------------------------- */

static void poll_status(struct system_app *a)
{
    char err[96];
    cJSON *st;

    err[0] = '\0';
    st = shell_ipc_call_timeout("sysd", "system.status", NULL, SHELL_IPC_UI_TIMEOUT_MS, err,
                                sizeof(err));
    system_view_apply_status(&a->view, st, a->clock_ms);
    if (st) {
        cJSON_Delete(st);
    }
    /* The card's expansion is shown on OVERVIEW only, so it is asked for
     * only there: a second bounded call, every other second. */
    if (a->tab == SYSTEM_TAB_OVERVIEW) {
        err[0] = '\0';
        st = shell_ipc_call_timeout("sysd", "storage.status", NULL, SHELL_IPC_UI_TIMEOUT_MS, err, sizeof(err));
        system_view_apply_storage(&a->view, st);
        cJSON_Delete(st);
    }
}

static void *system_create(lv_obj_t *root)
{
    struct system_app *a = calloc(1, sizeof(*a));
    char err[96];
    cJSON *info;

    if (!a) {
        return NULL;
    }
    a->root = root;
    system_view_init(&a->view);
    diag_view_init(&a->dv);
#if defined(POCKETOS_SHELL_TEST_HOOKS) && POCKETOS_SHELL_TEST_HOOKS
    {
        /* Simulator only: open on another tab, so a screenshot taken at
         * start shows it (tests/system_brand_shell_test.sh: the identity row
         * is on ABOUT). Compiled out of the panel's build. */
        const char *t = getenv("POCKETOS_TEST_SYSTEM_TAB");
        int i;

        for (i = 0; t && i < SYSTEM_TAB_COUNT; i++) {
            if (strcasecmp(t, tab_labels[i]) == 0) {
                a->tab = (enum system_tab)i;
            }
        }
    }
#endif

    /* Identity does not change while the system runs, so it is asked for once
     * and kept. A failure leaves it unknown rather than wrong; the next
     * screen visit asks again. */
    err[0] = '\0';
    info = shell_ipc_call_timeout("sysd", "system.info", NULL, SHELL_IPC_UI_TIMEOUT_MS, err,
                                  sizeof(err));
    system_view_apply_info(&a->view, info);
    if (info) {
        cJSON_Delete(info);
    }
    /* Region and backend are static too: one call, not a second poll. Skipped
     * entirely when the shell's own poll says radiod is not answering - there
     * is nothing to learn, and three bounded calls in a row on the LVGL
     * thread is 600 ms of no repaint on the one day every service is down. */
    err[0] = '\0';
    info = pocketos_shell_radio_state()
               ? shell_ipc_call_timeout("radiod", "radio.info", NULL, SHELL_IPC_UI_TIMEOUT_MS,
                                        err, sizeof(err))
               : NULL;
    if (info) {
        const cJSON *region = cJSON_GetObjectItemCaseSensitive(info, "region");
        const cJSON *backend = cJSON_GetObjectItemCaseSensitive(info, "backend");

        system_view_set_radio_detail(&a->view,
                                     cJSON_IsString(region) ? region->valuestring : NULL,
                                     cJSON_IsString(backend) ? backend->valuestring : NULL);
        cJSON_Delete(info);
    }
    system_view_set_radio_state(&a->view, pocketos_shell_radio_state());

    poll_status(a);
    build_frame(a);
    rebuild(a);
    /* Only now: building lays objects out as it goes, and the layout step
     * arranges objects that must all exist. */
    lv_obj_add_event_cb(a->frame, on_frame_size, LV_EVENT_SIZE_CHANGED, a);
    lv_obj_update_layout(a->frame);
    layout(a);
    return a;
}

static void system_tick(void *priv)
{
    struct system_app *a = priv;

    a->clock_ms += 1000;
    /* A machine that is on its way down has nothing left to report, and
     * asking a service that is being stopped only produces a timeout. */
    if (!system_view_is_polling(&a->view)) {
        return;
    }
    /* The radio state is whatever the status bar's own poll last saw. */
    system_view_set_radio_state(&a->view, pocketos_shell_radio_state());
    if (a->diag) {
        /* The page asks for what it shows, one call a tick, and nothing
         * else is polled meanwhile. */
        diag_step(a);
        diag_repaint(a);
        return;
    }
    if (a->tab == SYSTEM_TAB_ABOUT) {
        /* Nothing on it is live. */
        return;
    }
    if (++a->tick >= SYSTEM_POLL_TICKS) {
        a->tick = 0;
        poll_status(a);
    } else {
        /* No poll this second, but the age of the last one still moves. */
        system_view_refresh_freshness(&a->view, a->clock_ms);
    }
    if (a->tab == SYSTEM_TAB_NETWORK) {
        system_net_poll_step(a);
    }
    if (shape_changed(a)) {
        rebuild(a);
    } else {
        repaint(a);
    }
}

static void system_destroy(void *priv)
{
    struct system_app *a = priv;

    /* The frame outlives this by a moment, until the shell deletes the app's
     * objects; nothing may call back into a freed app in between. */
    if (a) {
        lv_obj_remove_event_cb_with_user_data(a->frame, on_frame_size, a);
    }
    free(priv);
}

LV_IMAGE_DECLARE(pos_app_icon_system);

/* The Back action and the header's back slab (app.h `back`,
 * `back_slab_in_app`): Diagnostics closes as its own Back button closes it,
 * back to SERVICES. The tabs are one level, so from any of them Back is the
 * shell's: to Settings, whose page System is (DS §47). */
static int system_back(void *priv)
{
    struct system_app *a = priv;

    if (!a || !a->diag) {
        return 0;
    }
    a->diag = false;
    rebuild(a);
    return 1;
}

