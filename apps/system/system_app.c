/*
 * System Status: the screen. Everything it *decides* is in system_view.c;
 * this builds the panels and turns taps into those decisions.
 *
 * Four short pages under a row of tabs (DS §52.5), in place of the one long
 * page with two scrolling columns it used to be:
 *
 *   OVERVIEW  CPU, temperature, memory, load, uptime, clock; storage; and
 *             Restart and Power off, last
 *   NETWORK   the interfaces, their addresses and their traffic; Wi-Fi; the
 *             LoRa radio and its packets; the mesh (system_net.c)
 *   SERVICES  the supervised services, and the way into Diagnostics
 *   ABOUT     the build, the card, the model, the kernel, the platform
 *
 * It reads nothing from the machine directly - no /proc, no /sys, no
 * /run/pocketos. system.info once at create, system.status every two seconds
 * over pocketipc while a page that shows it is up, and the radio state the
 * shell's status bar has already polled; the Network page adds one call a
 * second between radiod, netd and meshcored. Every call carries
 * SHELL_IPC_UI_TIMEOUT_MS, so a service that has stopped answering costs one
 * frame and never the session (unit A, M5).
 *
 * LAYOUT. Each page in two shapes, chosen from the body the app is given and
 * chosen again whenever that body changes size (see "the layout" below): the
 * panels one above the other when the body is tall, two to a row when it is
 * wide. The orientation is the system's (DS section 21.2); nothing here asks
 * what it is, only how much room there is.
 *
 * DIAGNOSTICS. A page of its own behind a button on SERVICES: a summary from
 * sysd, radiod and meshcored, the crash reports and the newest log lines with
 * All / Warnings / Errors, for diagnosing the device without SSH. What it
 * says is diag_view.c's; it refreshes one bounded call per tick
 * (diag_view.h), and holds at most DIAG_LOG_MAX log lines.
 *
 * Copyright (c) 2026 PocketOS authors.
 * SPDX-License-Identifier: Apache-2.0
 */
